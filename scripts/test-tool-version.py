#!/usr/bin/env python3
"""Check shared tool versions and generated assembly provenance."""

import argparse
import os
from pathlib import Path
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
TOOLS = ('dcc', 'dccpeep', 'dccrtlstrip', 'dccmake', 'm80c', 'l80c')


def tool(name):
    return ROOT / (name + ('.exe' if os.name == 'nt' else ''))


def run(*args):
    return subprocess.run([str(arg) for arg in args], check=True,
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                          universal_newlines=True).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--expected', help='required exact version for release builds')
    args = parser.parse_args()
    versions = {}
    for name in TOOLS:
        output = run(tool(name), '--version').strip()
        prefix = name + ' '
        if name == 'dcc':
            prefix = 'dcc (DCC C89->Z80 compiler) '
        assert output.startswith(prefix), (name, output)
        versions[name] = output[len(prefix):]
    assert len(set(versions.values())) == 1, versions
    version = versions['dcc']
    if args.expected:
        assert version == args.expected, (version, args.expected)

    with tempfile.TemporaryDirectory(prefix='dcc-version-') as directory:
        work = Path(directory)
        source = work / 'probe.c'
        raw = work / 'probe.mac'
        optimized = work / 'optimized.mac'
        runtime = work / 'rtlmin.mac'
        source.write_text('int main(void) { return 0; }\n')
        run(tool('dcc'), source, '-o', raw)
        run(tool('dccpeep'), raw, optimized)
        for path in (raw, optimized):
            assert path.read_text().splitlines()[0] == '; built with dcc ' + version
        run(tool('dccrtlstrip'), '--strip-apps', optimized)
        assert optimized.read_text().splitlines()[0] == '; built with dcc ' + version
        run(tool('dccrtlstrip'), '-r', ROOT / 'DCCRTL.MAC', '-o', runtime, optimized)
        assert runtime.read_text().splitlines()[0].startswith(
            '; generated by dccrtlstrip ' + version + ' ')
    print('Shared version and .MAC comments: ' + version)


if __name__ == '__main__':
    main()
