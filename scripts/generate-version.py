#!/usr/bin/env python3
"""Write the Git-derived host-tool version as a C header (Python 3.7+)."""

import argparse
from pathlib import Path
import re
import subprocess


ROOT = Path(__file__).resolve().parents[1]


def version(root):
    try:
        result = subprocess.run(
            ['git', 'describe', '--tags', '--always', '--dirty',
             '--match', 'v[0-9]*'],
            cwd=str(root), stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
            universal_newlines=True, check=True)
    except (OSError, subprocess.CalledProcessError):
        return 'unknown'
    value = result.stdout.strip()
    return value if re.fullmatch(r'[A-Za-z0-9._+-]+', value) else 'unknown'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args()
    value = version(args.root)
    content = ('/* Generated by scripts/generate-version.py; do not edit. */\n'
               '#ifndef DCC_VERSION_H\n#define DCC_VERSION_H\n'
               '#define DCC_BUILD_VERSION "{}"\n#endif\n'.format(value))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text() != content:
        args.output.write_text(content)
    print(value)


if __name__ == '__main__':
    main()
