    fputs("\tld l,(ix-2)\n\tld h,(ix-1)\n", out);
    fprintf(out, "\tjp L%d\nL%d:\n\tld hl,65535\nL%d:\n",
            ready, failed, ready);
    mir_endgame_emit_numeric_value(
        out, plan, print_call, format_string);
