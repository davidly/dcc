void load_input_file( void )
{
    char * result;
    char acLine[ 120 ];

    printf( "filename to read: " );
    fflush( stdout );
    result = gets( acLine );
    if ( result )
    {
        g_loadFile = fopen( result, "rb" );
        if ( !g_loadFile )
        {
            printf( "failed to open the file\n" );
            fflush( stdout );
        }
    }
}

int getc_load_file( void )
{
    char c;

    c = fgetc( g_loadFile );
    if ( 26 == c )            /* ^z eof on CP/M */
        return EOF;
    if ( 3 == c || 17 == c )  /* ^c or ^q */
        end_emulation();

    return c;
}

uint8_t m_load( uint16_t address )
{
    char ch;
    int next;

    if ( 0xd011 == address )
    {
        if ( g_loadFile )
        {
            next = getc_load_file();
            if ( EOF == next )
            {
                fclose( g_loadFile );
                g_loadFile = 0;
            }
            else
            {
                kbd_char = (char) next;
                kbd_available = true;
                return 0x80;
            }
        }

        if ( kbhit() )
        {
            ch = (char) getch();

            if ( 0xa == ch )
                ch = 0xd;

            if ( ch < 26 && 0x08 != ch && 0x0d != ch && 0x7f != ch )
            {
                if ( 17 == ch || 3 == ch )
                    end_emulation();
                else if ( 12 == ch )
                {
                    load_input_file();
                    if ( g_loadFile )
                        return 0x80;
                }
                else if ( 18 == ch )
                    soft_reset();

                return 0;
            }

            if ( 0x08 == ch || 0x7f == ch ) /* it's an apple 1 thing */
                ch = 0x5f;

            kbd_char = ch;
            kbd_available = true;
            return 0x80;
        }
        else
            return 0;
    }
    else if ( 0xd010 == address )
    {
        if ( kbd_available )
        {
            kbd_available = false;
            ch = kbd_char;
        }
        else
        {
            if ( kbhit() )
                ch = (char) getch();
            else
                ch = 0;
        }

        if ( 0 != ch )
        {
            ch = (char) toupper( ch );
            ch |= 0x80;
            set_byte( 0xd011, 0 );
            return ch;
        }
    }

    return get_byte( address );
}

void m_store( uint16_t address )
{
    char ch;

    if ( 0xd012 == address )
    {
        ch = 0x7f & get_byte( 0xd012 );
        if ( 0x7f != ch && 0x0a != ch )
        {
            if ( 0x0d == ch )
                ch = 0x0a;

            printf( "%c", ch );
            fflush( stdout );
        }
        set_byte( address, ch );
    }
}

static bool ishex( char c )
{
    return ( ( c >= 'A' && c <= 'F' ) || ( c >= 'a' && c <= 'f' ) || ( c >= ' ' && c <= '9' ) );
}

uint16_t hextoui( char * p )
{
    char c;
    uint16_t i, result;
    result = 0;

    while ( ' ' == *p )
        p++;

    while ( c = *p )
    {
        if ( c >= '0' && c <= '9' )
            i = c - '0';
        else if ( c >= 'a' && c <= 'f' )
            i = 10 + c - 'a';
        else if ( c >= 'A' && c <= 'F' )
            i = 10 + c - 'A';
        else
            break;

        result = result * 16 + i;
        p++;
    }

    return result;
}

static uint16_t read_hex( char * p, uint8_t len )
{
    uint16_t result;
    char save;
    save = p[ len ];
    p[ len ] = 0;

    result = hextoui( p );
    p[ len ] = save;
    return result;
}

static bool load_intel( FILE * fp )
{
    char * buf;
    uint8_t reclen, rectyp, x, val;
    uint16_t offset;
    char acLine[ 120 ];

    for ( ;; )
    {
        buf = fgets( acLine, _countof( acLine), fp );

        if ( buf && strlen( buf ) >= 11 )
        {
            if ( ':' != buf[ 0 ] )
                usage( "error: input Intel HEX file is malformed" );

            reclen = (uint8_t) read_hex( buf + 1, 2 );
            offset = read_hex( buf + 3, 4 );
            rectyp = (uint8_t) read_hex( buf + 7, 2 );

            if ( 1 == rectyp ) 
                break;

            if ( 0 != rectyp  )
                usage( "file format not recognized" );

            for ( x = 0; x < reclen; x++ )
            {
                if ( feof( fp ) )
                    usage( "malformed input file" );

                val = (uint8_t) read_hex( buf + ( 2 * x ) + 9, 2 );
                set_byte( offset + x, val );
            }
        }
        else
            break;
    }

    fclose( fp );
    return true;
}

bool loadFile( char * filePath )
{
    bool ok;
    FILE * fp;
    char c, *buf, *pcolon, *pnext;
    uint16_t run_address, a;
    uint8_t b;
    char acLine[ 120 ];

    run_address = 0;
    ok = false;
    fp = fopen( filePath, "r" );

    if ( 0 != fp )
    {
        c = (char) fgetc( fp );
        fclose( fp ); /* can't seek on cp/m reliably */
        fp = fopen( filePath, "r" );

        if ( ':' == c )
            return load_intel( fp );

        a = 0;

        do
        {
            buf = fgets( acLine, _countof( acLine), fp );

            if ( buf && strlen( buf ) >= 3 )
            {
                pcolon = strchr( buf, ':' );
                if ( !pcolon )
                    usage( "input hex file has a line without a colon, which is invalid" );

                if ( pcolon != buf )
                {
                    a = (uint16_t) hextoui( buf );

                    if ( run_address < 0x100 )
                    {
                        run_address = a;
    
                        if ( !g_fStartAddressSpecified )
                            g_startAddress = a;
                    }
                }

                pnext = pcolon + 1;
                ok = true;

                for ( ;; )
                {
                    while ( ' ' == *pnext )
                        pnext++;

                    if ( ishex( *pnext ) && ishex( * ( pnext + 1 ) ) )
                    {
                        b = (uint8_t) hextoui( pnext );
                        pnext += 2;
                        set_byte( a++, b );
                    }
                    else
                        break;
                }
            }
        } while ( !feof( fp ) );

        fclose( fp );
    }

    return ok;
}

void invoke_command( char * pcFile )
{
    bool ok;
    power_on();

    if ( pcFile )
    {
        ok = loadFile( pcFile );
        if ( !ok )
        {
            printf( "unable to load emulator input file %s\n", pcFile );
            exit( 1 );
        }
    }

    cpu.pc = g_startAddress;
    cpu.sp = 0xff;

    if ( g_useHooks )
    {
        set_byte( 0xff1f, OP_HOOK );   /* GETLINE monitor entry point */
        set_byte( 0xffdc, OP_HOOK );   /* PRBYTE. Prints the byte in A as a 2-digit hex number */
        set_byte( 0xffe5, OP_HOOK );   /* PRHEX. Prints the low nibble in A as hex */
        set_byte( 0xffef, OP_HOOK );   /* ECHO character in A to the terminal */
    }

    if ( g_exitOnMonitor )
        set_byte( 0xff1f, OP_HALT );   /* exit the emulator when when an app returns to wozmon */

    emulate();
}

int main( int argc, char * argv[] )
{
    int i;
    char * pcHEX, *parg, c, lower;
    pcHEX = 0;

    for ( i = 1; i < argc; i++ )
    {
        parg = argv[i];
        c = *parg;
    
        if ( '-' == c )
        {
            lower = (char) tolower( parg[1] );
    
            if ( 'a' == lower )
            {
                if ( ':' == parg[2] )
                {
                    parg += 3;
                    if ( '0' == parg[0] && ( 'X' == parg[1] || 'x' == parg[1] ) )
                        parg += 2;

                    g_startAddress = hextoui( parg );
                    g_fStartAddressSpecified = true;
                }
                else
                    usage( "colon required after a argument" );
            }
            else if ( 'h' == lower )
                g_useHooks = true;
            else if ( 'l' == lower )
            {
                g_loadFile = fopen( parg + 3, "rb" );
                if ( !g_loadFile )
                    usage( "unable to load the file specified" );
            }
            else if ( 'x' == lower )
                g_exitOnMonitor = true;
            else
                usage( "invalid command" );
        }
        else
        {
            if ( 0 == pcHEX )
                pcHEX = parg;
            else
                usage( "too many arguments" );
        }
    }
    
    if ( 0 == pcHEX && g_useHooks )
        usage( "no command specified and hooks means there is nothing to run" );
    
    memset( &cpu, 0, sizeof( cpu ) );
    invoke_command( pcHEX );
    printf( "\n" );
    return 0;
}

