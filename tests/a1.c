char * render_flags( void )
{
    ac_flags[ 0 ] = cpu.fNegative ? 'N' : 'n';
    ac_flags[ 1 ] = cpu.fOverflow ? 'V' : 'v';
    ac_flags[ 2 ] = cpu.fDecimal ? 'D' : 'd';
    ac_flags[ 3 ] = cpu.fInterruptDisable ? 'I' : 'i';
    ac_flags[ 4 ] = cpu.fZero ? 'Z' : 'z';
    ac_flags[ 5 ] = cpu.fCarry ? 'C' : 'c';
    ac_flags[ 6 ] = 0;
    return ac_flags;
}
